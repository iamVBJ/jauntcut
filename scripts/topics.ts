// Scans topics/*/reel.ts and writes src/topics.generated.ts so every topic
// shows up as its own composition. Creates a default music.json where missing.
// Runs automatically from `npm run media` and `npm run new`.
import { existsSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = "topics";
const slugs = readdirSync(dir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && !d.name.startsWith("_") && existsSync(join(dir, d.name, "reel.ts")))
  .map((d) => d.name)
  .sort();

for (const s of slugs) {
  const m = join(dir, s, "music.json");
  if (!existsSync(m)) {
    writeFileSync(m, JSON.stringify({ file: null, source: null, bpm: 100, firstBeat: 0, suggestedStart: 0, duration: 0 }, null, 2) + "\n");
  }
}

const lines = [
  "// Generated by scripts/topics.ts. Do not edit.",
  'import type { ReelInput } from "./schema";',
  ...slugs.flatMap((s, i) => [
    `import { reel as reel${i} } from "../topics/${s}/reel";`,
    `import track${i} from "../topics/${s}/music.json";`,
    existsSync(join(dir, s, "layout.json"))
      ? `import layout${i} from "../topics/${s}/layout.json";`
      : `const layout${i} = {};`,
    existsSync(join(dir, s, "tracks.json"))
      ? `import tracks${i} from "../topics/${s}/tracks.json";`
      : `const tracks${i} = {};`,
    existsSync(join(dir, s, "media.json"))
      ? `import media${i} from "../topics/${s}/media.json";`
      : `const media${i} = {};`,
  ]),
  "",
  `export const topics: (ReelInput & { track: unknown; layout: unknown; media: unknown; tracks: unknown })[] = [${slugs.map((_, i) => `{ ...reel${i}, track: track${i}, layout: layout${i}, media: media${i}, tracks: tracks${i} }`).join(", ")}];`,
  "",
];
writeFileSync("src/topics.generated.ts", lines.join("\n"));
console.log(`topics: ${slugs.join(", ") || "(none)"}`);
